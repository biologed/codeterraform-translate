"""
Вывод в консоль без сюрпризов с кодировкой.

ЗАЧЕМ. Все скрипты здесь печатают по-русски, а Python выбирает кодировку
вывода по окружению. Когда вывод идёт не в терминал, а в файл или в пайп
(как на сборочном сервере GitHub Actions), берётся системная кодировка -
и на англоязычной Windows это cp1252, в которой кириллицы нет. Скрипт
падает с UnicodeEncodeError на первой же русской строке, причём падает
ровно там, где просто печатал прогресс:

    print(f"[+] {name} {size} байт")
    UnicodeEncodeError: 'charmap' codec can't encode characters...

Ошибка обиднее, чем кажется: сама работа была сделана, развалился только
отчёт о ней. Поэтому в начале каждого скрипта переключаем вывод на UTF-8,
а на случай совсем экзотического окружения ставим errors="replace" -
пусть лучше пара символов покажется вопросиками, чем упадёт сборка.
"""

import sys


def enable_utf8_output():
    for stream in (sys.stdout, sys.stderr):
        # reconfigure появился в Python 3.7; у подменённых потоков
        # (например, в тестах) его может не быть вовсе.
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8", errors="replace")
            except (ValueError, OSError):
                pass
