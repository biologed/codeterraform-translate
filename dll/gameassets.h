#pragma once
#include <string>

// Доступ к фронтенду игры, вшитому в её собственный exe.
//
// ЗАЧЕМ. Чтобы подменить js-чанк с локализацией, нужен его ОРИГИНАЛ: мы
// вставляем в него свой каталог перевода. Раньше оригиналы доставались
// заранее, скриптом (tools/extract_assets.py), и складывались папкой рядом
// с DLL. Но имена чанков содержат хеш содержимого, поэтому после каждого
// обновления игры заготовленный патч переставал подходить и его надо было
// пересобирать руками.
//
// Здесь то же самое делается в рантайме: exe игры уже загружен в наш
// процесс (мы внутри него), значит его секцию .rdata можно читать напрямую
// по указателям, без единого обращения к диску. Оттуда берётся таблица
// ассетов Tauri, а из неё - сжатый brotli оригинал нужного файла.
namespace GameAssets {

    // Разбирает таблицу ассетов в образе игры. Вызывается один раз;
    // возвращает количество найденных файлов (0 - формат не опознан).
    size_t Load();

    // Отдаёт РАСПАКОВАННОЕ содержимое ассета по пути вида
    // "assets/i18n-Dh-M7E2V.js" (можно и с ведущим слэшем).
    // false, если такого файла в игре нет или он не распаковался.
    bool Read(const std::wstring& path, std::string& out);

}
