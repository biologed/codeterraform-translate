#pragma once
#include <windows.h>
#include <WebView2.h>

namespace AssetPatch {

    // Подключает подмену файлов игры: если рядом с DLL есть папка
    // locale_patch, любой запрос страницы к файлу, который в ней лежит,
    // будет обслужен ИЗ НЕЁ, а не из самой игры.
    //
    // Ради чего: в игре есть штатная система локализации (строки по ключам
    // + фолбэк на английский), и в неё можно добавить русский каталог -
    // тогда перевод делает сама игра, ДО того как текст попадёт на страницу.
    // Это принципиально надёжнее подмены текста в DOM: текст, который ввёл
    // игрок (код в редакторе, вывод его программ), не может быть задет в
    // принципе, а строки с подстановками ("Урон: {n}") наконец работают.
    // Патченные файлы готовит tools/make_locale_patch.py.
    //
    // Вызывается из WebViewHooks::OnControllerCreated до навигации.
    void Install(ICoreWebView2* webview);

    // Регистрирует обработчик ЕЩЁ РАЗ - после того, как свой зарегистрировала
    // сама игра (Tauri/wry обслуживает через WebResourceRequested собственный
    // протокол http://tauri.localhost и отдаёт файлы, вшитые в exe).
    //
    // Так надо, потому что при нескольких обработчиках WebView2 отдаёт
    // странице ответ ПОСЛЕДНЕГО, кто его выставил. Мы ставим свой хук раньше
    // игры (наш код исполняется до её колбэка создания контроллера), поэтому
    // первая регистрация всегда проигрывает: в лог писалось "файл подменён",
    // а страница получала оригинал из exe - ровно это и наблюдалось.
    //
    // Вызывается из hooks.cpp сразу после колбэка самой игры.
    void InstallLate(ICoreWebView2Controller* controller);

    // Перечитывает locale_ru.json и забывает уже пропатченные чанки, чтобы
    // они собрались заново с новым переводом. Сама страница при этом не
    // перезагружается - это делает вызывающий (хоткей F6 в webview.cpp).
    void ReloadLocale();

}
