#pragma once
#include <windows.h>
#include <WebView2.h>
#include <string>
#include <functional>

namespace WebViewHooks {

    // Вызывается один раз из hooks.cpp, когда игра создала
    // ICoreWebView2Controller. Отсюда достаётся ICoreWebView2
    // и запускается вся логика перевода.
    void OnControllerCreated(ICoreWebView2Controller* controller);

    // Выполняет произвольный JS в текущей странице.
    void ExecuteJs(const std::wstring& js);

    // Выполняет функцию на потоке, которому принадлежит WebView2 (потоке
    // окна игры), через очередь оконных сообщений. Нужна не только хоткеям:
    // на ней же построена отложенная выдача подменённых файлов в assets.cpp -
    // работа, поставленная в очередь, выполняется ПОСЛЕ текущего разбора
    // события, то есть после всех обработчиков самой игры.
    void RunOnUiThread(std::function<void()> fn);

    // Берёт document.body.innerText напрямую из результата ExecuteScript
    // (не через postMessage - в этой игре Tauri сам перехватывает канал
    // postMessage под собственный IPC) и сохраняет в dump.txt. Заодно
    // накапливает в dump_dom.json заготовку словаря из строк ТЕКУЩЕГО
    // экрана - только тех, что реально переводятся (зоны пользовательского
    // ввода пропускаются) и которых ещё нет в translations.json.
    //
    // Основной способ собрать строки игры - всё же не этот, а офлайновый:
    // tools/extract_assets.py + tools/dump_strings.py достают из exe сразу
    // весь каталог локализации целиком. Дамп с экрана нужен для того, что
    // игра собирает уже в рантайме и в каталоге не лежит.
    void DumpBodyText();

    // Пишет в dump_focus.txt, что за элемент сейчас под фокусом и под
    // курсором мыши: путь в DOM, классы и - главное - защищён ли он уже от
    // перевода (и каким именно селектором). Так подбираются значения для
    // settings.skipSelectors в translations.json: наводим мышь на консоль
    // или ставим курсор в редактор кода, жмём F7, смотрим файл.
    void DumpFocusInfo();

    // Берёт outerHTML (РАЗМЕТКУ, а не просто текст) элемента по CSS-селектору
    // (пустая строка - весь document.body) и сохраняет в dump_html.txt.
    // Работает через обычный ExecuteScript - основной способ увидеть
    // реальную структуру DOM (в частности, разбит ли текст на несколько
    // <span>/<p>/<div>, из-за чего точный словарь не матчится), раз DevTools
    // в этой игре по какой-то причине недоступны.
    void DumpBodyHtml(const std::wstring& cssSelector);

    // Перечитывает locale_ru.json и перезагружает страницу, чтобы новый
    // перевод собрался и применился без перезапуска игры (хоткей F6).
    // Страница при этом возвращается в исходное состояние - это инструмент
    // переводчика, а не способ играть.
    void ReloadLocale();

    // Перечитывает translations.json с диска и:
    //  1) обновляет скрипт, который автоматически внедряется при каждой
    //     навигации (AddScriptToExecuteOnDocumentCreated);
    //  2) сразу применяет новый перевод к уже открытой странице.
    // Вызывается по F11, чтобы не нужно было перезапускать игру
    // при правке словаря.
    void ReloadTranslations();

}
