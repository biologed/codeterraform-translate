#pragma once
#include <string>

// Перевод через собственную систему локализации игры - без заранее
// подготовленных файлов.
//
// Игра ищет перевод по ключу и, если не нашла, показывает английский
// исходник, вшитый рядом с ключом в код. Достаточно вклиниться в функцию
// поиска - и переводится всё, что игра вообще умеет переводить, включая
// строки с подстановками.
//
// Раньше эту врезку делал скрипт (tools/make_locale_patch.py), а результат
// складывался в папку locale_patch. Теперь то же самое умеет сама DLL:
// оригинал берётся из exe (см. gameassets.h), врезка ставится в памяти при
// первом запросе файла. Поэтому обновление игры больше ничего не ломает -
// имена чанков с хешами перестают иметь значение.
namespace Locale {

    // Читает locale_ru.json рядом с DLL (формат: {"группа": {"ключ": "текст"}},
    // как catalog.json из tools/dump_strings.py). Пустые значения
    // пропускаются: пусть игра покажет свой английский оригинал.
    // Возвращает количество загруженных строк.
    size_t Reload();

    // Есть ли что подставлять (иначе патчить файлы незачем).
    bool IsLoaded();

    // Врезает в исходник js-чанка выдачу нашего перевода. false, если в этом
    // файле нет функции поиска перевода (значит, это не тот чанк).
    bool PatchJs(const std::string& source, std::string& out);

}
